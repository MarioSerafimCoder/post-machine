import { test, expect } from '@playwright/test'

test('post editável com texto, ferramentas, teclado e upload local', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/#/studio')
  await page.getByRole('button', { name: 'Criar projeto vazio' }).click()
  await page.getByRole('button', { name: 'Adicionar título', exact: true }).click()
  await page.getByLabel('Texto do elemento').fill('Design com intenção')
  await page.getByLabel('Tamanho da fonte').fill('72')
  await page.getByRole('button', { name: 'Duplicar elemento', exact: true }).click()
  await expect(page.getByLabel('Texto do elemento')).toHaveValue('Design com intenção')
  await page.getByRole('button', { name: 'Excluir elemento' }).click()
  await page.getByRole('button', { name: 'Camadas', exact: true }).click()
  await expect(page.getByRole('button', { name: /Design com intenção/ })).toHaveCount(1)
  await page.getByRole('button', { name: 'Imagens', exact: true }).click()
  const png = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 400; c.height = 300; const ctx = c.getContext('2d')!; ctx.fillStyle = '#d8ed91'; ctx.fillRect(0,0,400,300); return c.toDataURL().split(',')[1] })
  await page.getByLabel('Adicionar ou substituir imagem').setInputFiles({ name: 'fixture.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
  await expect(page.getByRole('button', { name: 'Recortar quadrado' })).toBeVisible()
  await page.getByRole('button', { name: 'Recortar quadrado' }).click()
  await page.getByRole('button', { name: 'Camadas', exact: true }).click()
  await expect(page.getByRole('button', { name: /2 · image/i })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('campanha gera carrossel editável, troca template e organiza slides', async ({ page }) => {
  await page.goto('/#/radar')
  await page.getByRole('button', { name: 'Nova campanha', exact: true }).click()
  await page.getByLabel('Quantidade de slides').selectOption('3')
  await page.getByLabel('Conteúdo em JSON ou Markdown').fill(JSON.stringify({ schemaVersion: 1, campaign: { title: 'Carrossel de teste', objective: 'Educar', audience: 'Designers', tone: 'Profissional', format: 'carousel', caption: '', cta: 'Salve esta ideia' }, sources: [], slides: ['cover', 'content', 'cta'].map((role, i) => ({ order: i+1, role, title: `Título ${i+1}`, body: 'Conteúdo editorial editável.', imageBrief: '', layoutType: 'editorial' })) }))
  await page.getByRole('button', { name: 'Importar conteúdo', exact: true }).click()
  await page.getByRole('button', { name: 'Criar design no Studio' }).click()
  await expect(page.getByRole('region', { name: 'Slides', exact: true }).getByRole('button', { name: /Slide [123]$/ })).toHaveCount(3)
  page.on('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Templates', exact: true }).click()
  await page.getByRole('button', { name: 'Conteúdo textual', exact: true }).click()
  await page.getByRole('button', { name: 'Camadas', exact: true }).click()
  await page.getByRole('button', { name: /Título 1/ }).first().click()
  await expect(page.getByLabel('Texto do elemento')).toHaveValue('Título 1')
  await page.getByLabel('Texto do elemento').fill('Texto preservado')
  await page.getByRole('button', { name: 'Duplicar slide', exact: true }).click()
  await page.getByRole('button', { name: 'Slide para direita', exact: true }).click()
  await page.getByRole('button', { name: 'Excluir slide', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Slides', exact: true }).getByRole('button', { name: /Slide [123]$/ })).toHaveCount(3)
})
