import { readFile } from 'node:fs/promises'
import JSZip from 'jszip'
test('recupera imagens e histórico, restaura backup e exporta PNG e ZIP nas dimensões reais', async ({ page }) => {
  await page.goto('/#/studio')
  await page.getByRole('button', { name: 'Criar projeto vazio' }).click()
  await page.getByLabel('Projeto', { exact: true }).fill('Projeto persistente')
  await page.getByRole('button', { name: 'Adicionar título', exact: true }).click()
  await page.getByLabel('Texto do elemento').fill('Antes')
  await page.getByLabel('Texto do elemento').fill('Depois')
  await page.getByRole('button', { name: 'Desfazer', exact: true }).click()
  await page.getByRole('button', { name: 'Camadas', exact: true }).click()
  await page.getByRole('button', { name: /1 · Antes/ }).click()
  await expect(page.getByLabel('Texto do elemento')).toHaveValue('Antes')
  await page.getByRole('button', { name: 'Refazer', exact: true }).click()
  await page.getByRole('button', { name: /1 · Depois/ }).click()
  await expect(page.getByLabel('Texto do elemento')).toHaveValue('Depois')
  await page.getByRole('button', { name: 'Imagens', exact: true }).click()
  const png = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 1200; c.height = 900; c.getContext('2d')!.fillRect(0,0,1200,900); return c.toDataURL().split(',')[1] })
  await page.getByLabel('Adicionar ou substituir imagem').setInputFiles({ name: 'fixture.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
  await expect(page.getByRole('button', { name: 'Recortar quadrado' })).toBeVisible()
  await page.getByRole('button', { name: 'Duplicar slide', exact: true }).click()
  await page.getByRole('button', { name: 'Duplicar slide', exact: true }).click()
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('status', { name: '' }).filter({ hasText: /^Salvo$/ })).toBeVisible()
  const backupEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Backup completo', exact: true }).click()
  const backupFile = await backupEvent; const backup = await readFile(await backupFile.path())
  const parsed = await JSZip.loadAsync(backup)
  expect(Object.keys(parsed.files).filter(name => name.startsWith('assets/') && !name.endsWith('/'))).toHaveLength(1)
  await page.reload()
  await page.getByRole('button', { name: 'Abrir Projeto persistente', exact: true }).click()
  await page.getByRole('button', { name: 'Camadas', exact: true }).click()
  await expect(page.getByRole('button', { name: /2 · image/i })).toBeVisible()
  await page.getByLabel('Zoom', { exact: true }).selectOption('0.2')
  const pngEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar PNG', exact: true }).click()
  const exported = await readFile(await (await pngEvent).path())
  expect([exported.readUInt32BE(16), exported.readUInt32BE(20)]).toEqual([1080,1350])
  const zipEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar ZIP', exact: true }).click()
  const zip = await JSZip.loadAsync(await readFile(await (await zipEvent).path()))
  const names = Object.keys(zip.files)
  expect(names).toEqual(['01-Projeto-persistente.png','02-Projeto-persistente.png','03-Projeto-persistente.png'])
  for (const name of names) { const bytes = await zip.file(name)!.async('nodebuffer'); expect([bytes.readUInt32BE(16),bytes.readUInt32BE(20)]).toEqual([1080,1350]) }
  await page.getByRole('button', { name: 'Projetos', exact: true }).click()
  await page.getByLabel('Restaurar projeto ZIP').setInputFiles({ name: 'backup.zip', mimeType: 'application/zip', buffer: backup })
  await expect(page.getByLabel('Projeto', { exact: true })).toHaveValue('Projeto persistente (restaurado)')
})

test('falha de IndexedDB mantém alterações e permite retentativa', async ({ page }) => {
  await page.goto('/#/studio'); await page.getByRole('button', { name: 'Criar projeto vazio' }).click()
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByText('Salvo', { exact: true })).toBeVisible()
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.put
    Object.assign(window, { restoreIDB: () => { IDBObjectStore.prototype.put = original } })
    IDBObjectStore.prototype.put = function (...args) { if (this.name === 'projects') throw new DOMException('Quota simulada', 'QuotaExceededError'); return original.apply(this, args) }
  })
  await page.getByLabel('Projeto', { exact: true }).fill('Edição mantida após falha')
  await expect(page.getByText('Falha ao salvar', { exact: true })).toBeVisible()
  await page.evaluate(() => (window as unknown as { restoreIDB: () => void }).restoreIDB())
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByText('Salvo', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Abrir Edição mantida após falha', exact: true })).toBeVisible()
})

