import { expect, test } from '@playwright/test'

test('compara, aplica, preserva a arte e reabre headlines', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/radar')
  await page.getByRole('button', { name: 'Nova campanha', exact: true }).click()
  await page.getByRole('button', { name: 'Começar do zero', exact: true }).click()
  await page.getByLabel('Formato', { exact: true }).selectOption('post')
  await page.getByLabel('Conteúdo em JSON ou Markdown').fill(JSON.stringify({
    schemaVersion: 1, campaign: { title: 'Headline editorial', objective: 'Educar', audience: 'Designers', tone: 'Profissional', format: 'post', caption: '', cta: '' },
    sources: [], slides: [{ order: 1, role: 'cover', title: 'Design editorial', body: 'A tipografia organiza a leitura.', imageBrief: '', layoutType: 'editorial' }],
  }))
  await page.getByRole('button', { name: 'Importar conteúdo', exact: true }).click()
  await page.getByRole('button', { name: 'Melhorar headline', exact: true }).click()
  const campaign = page.getByRole('region', { name: 'Agente de Headlines' })
  await expect(campaign).toContainText('2 palavras')
  await campaign.getByRole('button', { name: 'Gerar propostas por regras' }).click()
  await expect(campaign).toContainText('A tipografia organiza a leitura')
  await campaign.getByRole('button', { name: 'Gerar sugestões com IA' }).click()
  await expect(campaign.getByLabel('Prompt de headlines')).toHaveValue(/Designers/)
  await campaign.getByLabel('Resposta de headlines').fill('não é JSON')
  await campaign.getByRole('button', { name: 'Importar sugestões', exact: true }).click()
  await expect(campaign.getByRole('alert')).toContainText('JSON válido')
  const title = 'Como a tipografia organiza a leitura'
  const suggestion = (text: string) => JSON.stringify({ schemaVersion: 1, suggestions: [{ id: 'headline-01', text, approach: 'informativa', rationale: 'Explicita o recorte da peça.', source: 'external-ai' }] })
  await campaign.getByLabel('Resposta de headlines').fill(suggestion(title))
  await campaign.getByRole('button', { name: 'Importar sugestões', exact: true }).click()
  await campaign.getByRole('button', { name: 'Favorita' }).click()
  await campaign.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.getByLabel('Título', { exact: true })).toHaveValue(title)
  await page.getByRole('button', { name: 'Criar design no Studio' }).click()
  await page.getByRole('button', { name: 'Camadas', exact: true }).click()
  const layer = page.getByRole('button', { name: /^2 ·/ })
  await layer.click()
  const text = page.getByLabel('Texto do elemento')
  const size = page.getByLabel('Tamanho da fonte')
  const position = page.getByLabel('X', { exact: true })
  const originalSize = await size.inputValue()
  const originalPosition = await position.inputValue()
  await expect(text).toHaveValue(title)
  await page.getByRole('button', { name: 'Melhorar título' }).click()
  const studio = page.getByRole('region', { name: 'Agente de Headlines' })
  await expect(studio.getByRole('button', { name: 'Favorita' })).toHaveAttribute('aria-pressed', 'true')
  for (const width of [1024, 1280, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await studio.getByText('Importar sugestões em JSON', { exact: true }).click()
  const longTitle = 'Tipografia e organização da leitura '.repeat(12).trim()
  await studio.getByLabel('Resposta de headlines').fill(suggestion(longTitle))
  await studio.getByRole('button', { name: 'Importar sugestões', exact: true }).click()
  const proposed = studio.getByRole('article').filter({ hasText: longTitle })
  await expect(proposed).toContainText('excede a altura')
  await proposed.getByRole('button', { name: 'Aplicar' }).click()
  await expect(studio.getByRole('status')).toContainText('excede a altura')
  await expect(text).toHaveValue(longTitle)
  await expect(size).toHaveValue(originalSize)
  await expect(position).toHaveValue(originalPosition)
  await page.getByRole('button', { name: 'Desfazer', exact: true }).click()
  await layer.click()
  await expect(text).toHaveValue(title)
  await page.getByRole('button', { name: 'Refazer', exact: true }).click()
  await layer.click()
  await expect(text).toHaveValue(longTitle)
  await page.getByRole('button', { name: 'Projetos', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Abrir Headline editorial' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Abrir Headline editorial' }).click()
  await page.getByRole('button', { name: 'Camadas', exact: true }).click()
  await layer.click()
  await expect(text).toHaveValue(longTitle)
  await page.getByRole('button', { name: 'Melhorar título' }).click()
  await expect(studio.getByText('Histórico de títulos')).toBeVisible()
  expect(errors).toEqual([])
})
