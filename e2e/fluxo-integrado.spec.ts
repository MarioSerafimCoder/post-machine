import { expect, test } from '@playwright/test'
import JSZip from 'jszip'
import { readFile } from 'node:fs/promises'

test('oportunidade chega à fabricação e mantém destaque editado no histórico, backup e exportação', async ({page}, info) => {
  test.skip(info.project.name === 'laptop', 'O fluxo completo passa no perfil desktop')
  const button=(name: string) => page.getByRole('button',{name,exact:true})
  await page.goto('/#/radar')
  await button('Oportunidades').click()
  await page.getByRole('region',{name:'Oportunidades editoriais'}).getByRole('button',{name:'Criar pauta',exact:true}).first().click()
  await page.getByLabel('Quantidade de slides').selectOption('2')
  await button('Gerar prompt para IA').click()
  await expect(page.getByLabel('Prompt editorial')).toHaveValue(/Separe fatos verificáveis/)
  const initial='Cor e ação no quadro'
  await page.getByLabel('Conteúdo em JSON ou Markdown').fill(JSON.stringify({
    schemaVersion:1, campaign:{title:'Fluxo editorial QA', objective:'Educar', audience:'Designers', tone:'Profissional',
      format:'carousel', caption:'Legenda já importada.', cta:'Volte à capa'},
    slides:[{order:1,role:'cover',title:initial,body:'Uma leitura visual.',imageBrief:'',layoutType:'editorial'},
      {order:2,role:'cta',title:'Fechamento',body:'Compare os exemplos.',imageBrief:'',layoutType:'editorial'}], sources:[],
  }))
  await button('Importar conteúdo').click()
  await button('Explorar designs da campanha').click()
  await expect(page.getByLabel('Nome do projeto')).toHaveValue('Fluxo editorial QA')
  await page.getByRole('navigation',{name:'Etapas da criação'}).getByRole('button',{name:'Templates',exact:true}).click()
  await page.getByRole('article').filter({hasText:'Narrativa Visual'}).getByRole('button',{name:'Usar coleção',exact:true}).click()
  await button('Prévia').click()
  await button('Montar meu carrossel').click()
  await expect(page.getByRole('region',{name:'Opções de design'}).getByRole('article')).toHaveCount(3)
  await button('Usar esta versão').click()
  await button('Camadas').click()
  await page.getByRole('button',{name:/Cor e ação no quadro/}).click()
  const title=page.getByLabel('Texto do elemento')
  await page.getByText('Destaque do título',{exact:true}).click()
  await title.evaluate(node => (node as HTMLTextAreaElement).setSelectionRange(6,10))
  await button('Destacar seleção').click()
  await title.fill('🎨 '+initial)
  await button('Desfazer').click()
  await page.getByRole('button',{name:/Cor e ação no quadro/}).click()
  await expect(title).toHaveValue(initial)
  await button('Refazer').click()
  await page.getByRole('button',{name:/🎨 Cor e ação no quadro/}).click()
  await expect(title).toHaveValue('🎨 '+initial)
  const frame1=button('Slide 1'),frame2=button('Slide 2')
  await frame1.press('ArrowRight')
  await expect(frame2).toBeFocused()
  await expect(frame2).toHaveAttribute('aria-pressed','true')
  await frame2.press('Alt+ArrowLeft')
  await expect(frame1).toBeFocused()
  await expect(frame1).toContainText('Encerramento')
  await frame1.press('Alt+ArrowRight')
  await expect(frame2).toHaveAttribute('aria-pressed','true')

  await button('Finalizar e exportar').click()
  await expect(page.getByRole('textbox',{name:'Legenda',exact:true})).toHaveValue('Legenda já importada.')
  await expect(page.getByRole('region', { name: 'Central de exportação' }).getByText('Revisão atual',{exact:true})).toBeVisible()
  const zipDownload=page.waitForEvent('download')
  await button('Exportar ZIP').click()
  const warning=button('Exportar com avisos')
  if(await Promise.race([zipDownload.then(()=>false),warning.waitFor().then(()=>true)])) await warning.click()
  const zip=await JSZip.loadAsync(await readFile(await (await zipDownload).path()))
  expect(Object.keys(zip.files).filter(name=>name.endsWith('.png'))).toEqual(['01-Fluxo-editorial-QA.png','02-Fluxo-editorial-QA.png'])
  await button('Fechar exportação').click()
  await page.getByText('Mais ações',{exact:true}).click()
  const backupDownload=page.waitForEvent('download')
  await button('Backup completo').click()
  const blob=await readFile(await (await backupDownload).path())
  const backup=await JSZip.loadAsync(blob)
  const project=JSON.parse(await backup.file('project.json')!.async('string'))
  const object=project.slides[0].scene.objects.find((item: {semantic:string})=>item.semantic==='title')
  expect(object).toMatchObject({text:'🎨 '+initial, styles:[{start:8,end:12,style:{fill:'#d60016'}}]})
  const campaignId=project.campaignId
  expect(campaignId).toMatch(/^[\da-f-]{36}$/)
  await button('Projetos').click()
  await page.getByLabel('Restaurar projeto ZIP').setInputFiles({name:'qa.zip',mimeType:'application/zip',buffer:blob})
  await expect(page.getByLabel('Projeto',{exact:true})).toHaveValue('Fluxo editorial QA (restaurado)')
})
