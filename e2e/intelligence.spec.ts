import { expect, test, type Page } from '@playwright/test'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const assistant = (page: Page) => page.getByRole('complementary', { name: 'Assistente Editorial', exact: true })

test('usa uma oportunidade real, aplica ao briefing e persiste silenciamento e feedback', async ({ page }) => {
  await page.goto('/#/radar')
  await button(page, 'Oportunidades').click()
  await page.getByRole('region', { name: 'Oportunidades editoriais' }).getByRole('button', { name: 'Criar pauta', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Inteligência editorial', exact: true })).toBeVisible()
  const dock = assistant(page)
  const launcher = button(page, 'Assistente Editorial')
  const balloon = dock.getByRole('region', { name: 'Insight editorial' })
  await expect(balloon).toBeVisible()
  await balloon.getByRole('button', { name: 'Ver detalhes' }).click()
  await expect(dock.getByRole('heading', { name: 'Assistente Editorial', exact: true })).toBeFocused()
  await dock.getByRole('button', { name: 'Abrir briefing', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Briefing editorial', exact: true })).toBeFocused()

  const intelligence = page.getByRole('region', { name: 'Inteligência editorial' })
  await intelligence.getByText('Contexto e perfil', { exact: true }).click()
  await intelligence.getByLabel('Canal de destino').selectOption('LinkedIn')
  await intelligence.getByLabel('Acesso às fontes').selectOption('unavailable')
  await intelligence.getByText(/^Recomendações · /).click()
  const format = page.getByLabel('Formato', { exact: true })
  const unchanged = await format.inputValue()
  await intelligence.getByRole('button', { name: 'Manter briefing atual', exact: true }).click()
  await expect(format).toHaveValue(unchanged)
  await button(page, 'Gerar prompt para IA').click()
  await expect(page.getByLabel('Prompt editorial')).toHaveValue(/Canal de destino: LinkedIn/)
  await expect(page.getByLabel('Prompt editorial')).toHaveValue(/Acesso à fonte marcado como indisponível/)
  await button(page, 'Salvar campanha').click()
  await expect(page.getByText('Campanha salva.', { exact: true })).toBeVisible()

  await launcher.press('Enter')
  await dock.getByLabel('Notificações').selectOption('muted')
  await page.keyboard.press('Escape')
  await expect(launcher).toBeFocused()
  await page.getByRole('link', { name: 'Studio', exact: true }).click()
  await launcher.click()
  await expect(dock).toContainText('Abra uma pauta')
  await expect(dock).not.toContainText('A fonte foi marcada como inacessível')
  await page.reload()
  await launcher.click()
  await expect(dock.getByLabel('Notificações')).toHaveValue('muted')
  await dock.getByText('Histórico e preferências', { exact: true }).click()
  await expect(dock).toContainText('Dispensado')
  page.once('dialog', dialog => void dialog.accept())
  await button(page, 'Redefinir memória editorial').click()
  await expect(dock).toContainText('Sem decisões registradas')
  await dock.getByLabel('Notificações').selectOption('proactive')
})

test('aplica recomendação explícita, preserva insights de headline e respeita movimento reduzido', async ({ page, context }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#/radar')
  await button(page, 'Pautas e prompts').click()
  await button(page, 'Nova campanha').click()
  await button(page, 'Começar do zero').click()
  const dock = assistant(page)
  await expect.poll(() => dock.locator('img').evaluate(img => (img as HTMLImageElement).currentSrc)).toMatch(/avatar\.png$/)
  const intelligence = page.getByRole('region', { name: 'Inteligência editorial' })
  await intelligence.getByText(/^Recomendações · /).click()
  const format = page.getByLabel('Formato', { exact: true })
  await expect(format).toHaveValue('carousel')
  const post = intelligence.getByRole('article').filter({ hasText: 'Considere um post único' })
  page.once('dialog', dialog => void dialog.dismiss())
  await post.getByRole('button', { name: 'Aplicar recomendação' }).click()
  await expect(format).toHaveValue('carousel')
  page.once('dialog', dialog => void dialog.accept())
  await post.getByRole('button', { name: 'Aplicar recomendação' }).click()
  await expect(format).toHaveValue('post')
  await context.setOffline(true)
  await button(page, 'Gerar prompt para IA').click()
  await expect(page.getByLabel('Prompt editorial')).toHaveValue(/Formato: Post único \| peças: 1/)
  await page.getByLabel('Conteúdo em JSON ou Markdown').fill(JSON.stringify({
    schemaVersion: 1, campaign: { title: 'Ensaio de headline', objective: 'Informar', audience: '', tone: 'Profissional', format: 'post', caption: '', cta: '' },
    sources: [], slides: [{ order: 1, role: 'content', title: 'Uma coisa incrível', body: 'Redesenho de uma identidade local.', imageBrief: '', layoutType: 'editorial' }],
  }))
  await button(page, 'Importar conteúdo').click()
  await button(page, 'Melhorar headline').click()
  await button(page, 'Assistente Editorial').click()
  await expect(dock).toContainText('Há termos genéricos')
  await dock.getByRole('button', { name: 'Abrir análise do título' }).click()
  await expect(page.locator('.headline-diagnosis')).toBeFocused()
})

test('usa aviso da fabricação e abre o slide correspondente', async ({ page }, info) => {
  await page.goto('/#/studio')
  await button(page, 'Produção Expressa').click()
  await page.getByRole('textbox', { name: /Cole aqui/ }).fill(`Slide 1 — Capa curta\n\nSlide 2 — Explicação detalhada\n${'Um exemplo que precisa de espaço de leitura. '.repeat(140)}`)
  await button(page, 'Organizar slides').click()
  await button(page, 'Prévia').click()
  await button(page, 'Fabricar meu carrossel').click()
  await expect(page.getByRole('region', { name: 'Propostas de fabricação' }).getByRole('article')).toHaveCount(3)
  await button(page, 'Assistente Editorial').click()
  const dock = assistant(page)
  await expect(dock).toContainText('Revise o slide 2 da proposta')
  await expect(dock).toContainText('Texto excede o espaço disponível.')
  await page.screenshot({ path: info.outputPath('assistente-fabricacao.png') })
  await dock.getByRole('button', { name: 'Ver slide da proposta' }).click()
  await expect(page.locator('#express-proposal-preview')).toBeFocused()
  await expect(button(page, 'Prévia do slide 2')).toHaveAttribute('aria-pressed', 'true')
})

test('localiza achado real da auditoria e retira recomendação obsoleta', async ({ page }, info) => {
  test.skip(info.project.name === 'laptop', 'Este cenário percorre os quatro viewports desktop')
  await page.goto('/#/studio')
  await button(page, 'Criar projeto vazio').click()
  await button(page, 'Adicionar título').click()
  await page.getByText('Propriedades avançadas', { exact: true }).click()
  const x = page.getByLabel('X', { exact: true })
  await x.fill('20')
  await button(page, 'Auditar design').click()
  await button(page, 'Auditar slide atual').click()
  await expect(page.getByRole('heading', { name: 'Texto fora da margem segura', exact: true })).toBeVisible()
  const dock = assistant(page)
  const launcher = button(page, 'Assistente Editorial')
  for (const [width, height] of [[1024, 768], [1280, 800], [1440, 900], [1920, 1080]]) {
    await page.setViewportSize({ width, height })
    const [panel, launch] = await Promise.all([page.getByRole('region', { name: 'Slides', exact: true }).boundingBox(), launcher.boundingBox()])
    expect(panel!.x + panel!.width).toBeLessThan(launch!.x)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    await page.screenshot({ path: info.outputPath(`studio-assistente-${width}.png`) })
  }
  await launcher.click()
  await expect(dock).toContainText('Texto fora da margem segura')
  await page.screenshot({ path: info.outputPath('assistente-auditoria.png') })
  await dock.getByRole('button', { name: 'Localizar ocorrência' }).click()
  await expect(page.getByLabel('Texto do elemento')).toBeVisible()
  await page.getByLabel('Texto do elemento').fill('Outra versão com nova legenda')
  await launcher.click()
  await expect(dock.getByRole('button', { name: 'Localizar ocorrência' })).toHaveCount(0)
  await page.setViewportSize({ width: 1000, height: 800 })
  await expect(launcher).toBeHidden()
})
