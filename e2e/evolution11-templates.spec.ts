import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import JSZip from 'jszip'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })

async function authorTemplate(page: Page) {
  await page.goto('/#/studio')
  await button(page, 'Criar projeto vazio').click()
  await button(page, 'Adicionar título').click()
  await page.getByLabel('Texto do elemento').fill('Título da composição original')
  await page.getByLabel('Função no template').selectOption('title')
  await button(page, 'Adicionar texto').click()
  await page.getByLabel('Texto do elemento').fill('Corpo original')
  await page.getByLabel('Função no template').selectOption('body')
  await page.getByText('Propriedades avançadas', { exact: true }).click()
  await page.getByLabel('Y', { exact: true }).fill('480')
  await button(page, 'Elementos').click()
  await button(page, 'Retângulo').click()
  await page.getByLabel('Função no template').selectOption('fixed')
  await page.getByLabel('Y', { exact: true }).fill('980')
  await page.getByText('Mais ações', { exact: true }).click()
  await button(page, 'Salvar como template').click()
  const dialog = page.getByRole('dialog', { name: 'Salvar como template' })
  await dialog.getByLabel('Nome do template').fill('Caderno de direção')
  await dialog.getByLabel('Finalidade editorial').fill('Educação')
  await dialog.getByLabel('Descrição opcional').fill('Estrutura para a série de tipografia.')
  await dialog.getByRole('button', { name: 'Salvar template', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await button(page, 'Projetos').click()
}

test('reabre e reutiliza composições autorais com conteúdo integral e editável', async ({ page, context }) => {
  await authorTemplate(page)
  await page.close()
  const returned = await context.newPage()
  await returned.goto('/#/studio')
  await button(returned, 'Produção Expressa').click()
  await returned.getByRole('textbox', { name: /Cole aqui/ }).fill('Slide 1 — A fala da tipografia\nO corpo segue integral no Studio.')
  await button(returned, 'Organizar slides').click()
  await button(returned, 'Templates').click()
  const library = returned.getByRole('region', { name: 'Meus templates' })
  await library.getByLabel('Filtrar por formato').selectOption('square')
  await expect(library.getByText('Nenhum template corresponde aos filtros.')).toBeVisible()
  await library.getByLabel('Filtrar por formato').selectOption('portrait')
  await library.getByLabel('Filtrar por finalidade').selectOption('Educação')
  await expect(library.getByRole('img', { name: 'Miniatura de Caderno de direção' })).toBeVisible()
  await library.getByRole('button', { name: 'Usar template' }).click()
  await button(returned, 'Prévia').click()
  await button(returned, 'Fabricar meu post').click()
  await expect(returned.getByRole('img', { name: 'Prévia do slide 1' })).toBeVisible()
  await button(returned, 'Usar esta versão').click()
  await button(returned, 'Camadas').click()
  await returned.getByRole('button', { name: /A fala da tipografia/ }).click()
  await expect(returned.getByLabel('Texto do elemento')).toHaveValue('A fala da tipografia')
  await expect(returned.getByLabel('Função no template')).toHaveValue('title')
  await returned.getByRole('button', { name: /O corpo segue integral/ }).click()
  await expect(returned.getByLabel('Texto do elemento')).toHaveValue('O corpo segue integral no Studio.')
  await returned.getByRole('button', { name: /Retângulo/ }).click()
  await expect(returned.getByLabel('Função no template')).toHaveValue('fixed')
  await button(returned, 'Projetos').click()
  await button(returned, 'Biblioteca de templates').click()
  const card = returned.getByRole('region', { name: 'Meus templates' }).getByRole('article').filter({ hasText: 'Caderno de direção' })
  await card.getByText('Gerenciar template').click()
  const downloaded = returned.waitForEvent('download')
  await card.getByRole('button', { name: 'Exportar backup' }).click()
  const archive = await downloaded
  const data = await readFile(await archive.path())
  const zip = await JSZip.loadAsync(data)
  const backup = JSON.parse(await zip.file('template.json')!.async('string'))
  expect(backup.design.slides[0].scene.objects.map((object: { text?: string }) => object.text)).toContain('Título da composição original')
  returned.once('dialog', dialog => void dialog.accept())
  await card.getByRole('button', { name: 'Excluir template' }).click()
  await expect(card).toHaveCount(0)
  await returned.getByLabel('Importar backup de template').setInputFiles({ name: 'template.zip', mimeType: 'application/zip', buffer: data })
  await expect(card).toBeVisible()
})

test('protege edições simultâneas e permite editar, favoritar e duplicar', async ({ page, context }) => {
  await authorTemplate(page)
  await button(page, 'Biblioteca de templates').click()
  const other = await context.newPage()
  await other.goto('/#/studio')
  await button(other, 'Biblioteca de templates').click()
  for (const tab of [page, other]) {
    const card = tab.getByRole('region', { name: 'Meus templates' }).getByRole('article')
    await card.getByText('Gerenciar template').click()
    await card.getByRole('button', { name: 'Renomear' }).click()
  }
  await page.getByLabel('Novo nome').fill('Caderno revisado')
  await button(page, 'Salvar nome').click()
  await expect(page.getByRole('heading', { name: 'Caderno revisado' })).toBeVisible()
  await other.getByLabel('Novo nome').fill('Sobrescrita de teste')
  await button(other, 'Salvar nome').click()
  await expect(other.getByRole('dialog').getByRole('alert')).toContainText('mudou em outra aba')
  await button(other, 'Fechar').click()
  await expect(other.getByRole('heading', { name: 'Caderno revisado' })).toBeVisible()
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Caderno revisado', exact: true }) })
  await card.getByRole('button', { name: 'Favorito' }).click()
  await expect(card.getByRole('button', { name: 'Favorito' })).toHaveAttribute('aria-pressed', 'true')
  await card.getByRole('button', { name: 'Duplicar' }).click()
  await expect(page.getByRole('heading', { name: 'Caderno revisado (cópia)' })).toBeVisible()
  await card.getByRole('button', { name: 'Editar no Studio' }).click()
  await page.getByText('Mais ações', { exact: true }).click()
  await button(page, 'Atualizar template').click()
  const update = page.getByRole('dialog', { name: 'Atualizar template' })
  await update.getByLabel('Descrição opcional').fill('Descrição editada no Studio.')
  await update.getByRole('button', { name: 'Salvar template' }).click()
  await expect(update).toHaveCount(0)
  await button(page, 'Projetos').click()
  await button(page, 'Biblioteca de templates').click()
  await expect(card.getByText('Descrição editada no Studio.')).toBeVisible()
})
