import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function openVirals(page: Page) {
  await page.goto('/#/radar')
  await page.getByRole('button', { name: 'Virais e formatos', exact: true }).click()
  return page.getByRole('region', { name: 'Virais e formatos', exact: true })
}

test('catálogo e biblioteca manual com fixture, filtros e backup', async ({ page }) => {
  const virals = await openVirals(page)
  await expect(virals).toContainText('Sua biblioteca está vazia')
  await virals.getByRole('button', { name: 'Ver catálogo de formatos' }).click()
  await expect(virals.locator('details')).toHaveCount(8)
  await virals.getByText('Antes e depois', { exact: true }).click()
  await expect(virals).toContainText('Antes, decisão, depois e aprendizado')
  await virals.getByRole('button', { name: 'Biblioteca de referências' }).click()
  await virals.getByRole('button', { name: 'Adicionar referência' }).click()
  const form = virals.getByRole('form')
  await form.getByLabel('Título da referência').fill('Arquitetura editorial')
  await form.getByLabel('URL original').fill('javascript:alert(1)')
  await form.getByRole('button', { name: 'Salvar referência' }).click()
  await expect(form.getByRole('alert')).toContainText('HTTP ou HTTPS')
  await form.getByLabel('URL original').fill('https://www.behance.net/gallery/123456/Fixture')
  await form.getByLabel('Nicho', { exact: true }).fill('Arquitetura')
  await form.getByLabel('Gancho').fill('Abertura com contraste visual')
  await form.getByRole('button', { name: 'Salvar referência' }).click()
  const detail = virals.getByRole('region', { name: 'Detalhes da referência' })
  await expect(detail).toContainText('Abertura com contraste visual')
  await detail.getByRole('button', { name: 'Editar referência' }).click()
  await form.getByLabel('Descrição').fill('Análise da estrutura editorial.')
  await form.getByRole('button', { name: 'Salvar referência' }).click()
  const cards = virals.locator('article')
  await cards.getByRole('button', { name: 'Favoritar' }).click()
  await expect(cards.getByRole('button', { name: 'Favoritar' })).toHaveAttribute('aria-pressed', 'true')
  await virals.getByLabel('Buscar referências').fill('estrutura')
  await expect(cards).toHaveCount(1)
  await virals.getByRole('combobox', { name: 'Plataforma' }).selectOption('pinterest')
  await expect(cards).toHaveCount(0)
  await virals.getByRole('combobox', { name: 'Plataforma' }).selectOption('behance')
  await expect(cards).toHaveCount(1)
  for (const width of [1024, 1280, 1440]) {
    await page.setViewportSize({ width, height: 960 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  const download = page.waitForEvent('download')
  await virals.getByRole('button', { name: 'Exportar biblioteca' }).click()
  const backup = await readFile(await (await download).path())
  await page.reload()
  await page.getByRole('button', { name: 'Virais e formatos', exact: true }).click()
  await expect(cards.getByRole('button', { name: 'Favoritar' })).toHaveAttribute('aria-pressed', 'true')
  await virals.getByRole('button', { name: 'Adicionar referência' }).click()
  await form.getByLabel('Título da referência').fill('Duplicata')
  await form.getByLabel('URL original').fill('https://behance.net/gallery/123456/Outra')
  await form.getByRole('button', { name: 'Salvar referência' }).click()
  await expect(virals.getByRole('alert')).toContainText('Já existe')
  await form.getByRole('button', { name: 'Cancelar' }).click()
  await cards.getByRole('button', { name: 'Ver detalhes' }).click()
  page.on('dialog', dialog => dialog.accept())
  await detail.getByRole('button', { name: 'Excluir referência' }).click()
  await expect(cards).toHaveCount(0)
  await virals.getByLabel('Restaurar biblioteca JSON').setInputFiles({ name: 'biblioteca.json', mimeType: 'application/json', buffer: backup })
  await expect(cards).toContainText('Arquitetura editorial')
})

test('cria pauta com origem criativa e abre o resultado no Studio', async ({ page }) => {
  const virals = await openVirals(page)
  await virals.getByRole('button', { name: 'Adicionar referência' }).click()
  await virals.getByLabel('Título da referência').fill('Formas de comparar soluções')
  await virals.getByLabel('URL original').fill('https://youtu.be/abcdefghijk')
  await virals.getByLabel('Mecanismo criativo').fill('Comparação com critérios iguais')
  await virals.getByRole('button', { name: 'Salvar referência' }).click()
  await expect(virals.getByRole('region', { name: 'Detalhes da referência' })).toContainText('Métricas não conectadas')
  await virals.getByRole('button', { name: 'Criar pauta com esta referência' }).click()
  const origin = page.getByRole('region', { name: 'Referência criativa de origem' })
  await expect(origin.getByRole('link')).toHaveAttribute('href', 'https://youtu.be/abcdefghijk')
  await page.getByLabel('Formato', { exact: true }).selectOption('post')
  await page.getByRole('button', { name: 'Gerar prompt para IA', exact: true }).click()
  await expect(page.getByLabel('Prompt editorial')).toHaveValue(/Comparação com critérios iguais/)
  await page.getByLabel('Conteúdo em JSON ou Markdown').fill(JSON.stringify({ schemaVersion: 1,
    campaign: { title: 'Design da referência', objective: 'Educar', audience: 'Designers', tone: 'Profissional', format: 'post', caption: '', cta: '' },
    slides: [{ order: 1, role: 'content', title: 'Critérios para comparar', body: 'Comece pelo objetivo.', layoutType: 'editorial', imageBrief: '' }], sources: [],
  }))
  await page.getByRole('button', { name: 'Importar conteúdo', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Revisão editorial' }).locator('..').getByRole('link', { name: 'Formas de comparar soluções' })).toBeVisible()
  await page.getByRole('button', { name: 'Criar design no Studio' }).click()
  await expect(page.getByLabel('Projeto', { exact: true })).toHaveValue('Design da referência')
  await page.getByRole('link', { name: 'Radar', exact: true }).click()
  await page.getByRole('button', { name: 'Virais e formatos', exact: true }).click()
  await expect(virals.locator('article')).toContainText('Formas de comparar soluções')
})
