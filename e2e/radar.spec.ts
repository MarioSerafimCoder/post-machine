import { test, expect } from '@playwright/test'

test('Radar carrega notícias reais, filtra e mantém favorito após recarregar', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/#/radar')
  await expect(page.getByRole('heading', { name: 'Radar Criativo' })).toBeVisible()
  const taxonomy = page.getByRole('combobox', { name: 'Categoria', exact: true })
  await expect(taxonomy.locator('option')).toHaveCount(8)
  await page.getByRole('button', { name: 'Mais filtros' }).click()
  await expect(page.getByRole('combobox', { name: 'Recorte', exact: true })).toBeVisible()
  const cards = page.getByRole('article')
  await expect(cards.first()).toBeVisible()
  await expect(page.getByText('Última coleta bem-sucedida:', { exact: false })).toBeVisible()
  await expect(page.getByText(/fontes (indisponíveis na última tentativa|consultadas)|itens pertinentes na última coleta/)).toHaveCount(0)
  const title = await cards.first().getByRole('heading').innerText()
  await page.getByRole('searchbox', { name: 'Buscar notícias' }).fill(title)
  await expect(cards.first().getByRole('link',{ name:title, exact:true })).toHaveAttribute('href', /^https?:\/\//)
  const favorite = page.getByRole('button', { name: `Favoritar: ${title}`, exact:true })
  await favorite.click()
  await expect(favorite).toHaveAttribute('aria-pressed','true')
  await page.reload()
  await page.getByRole('button', { name: 'Mais filtros' }).click()
  await page.getByRole('combobox', { name: 'Recorte', exact: true }).selectOption('direct')
  await page.getByRole('checkbox', { name:'Só favoritos' }).check()
  await expect(cards).toHaveCount(1)
  await expect(favorite).toHaveAttribute('aria-pressed','true')
  await page.getByRole('searchbox').fill('zzzzzzzzzzzz')
  await expect(page.getByText('Nenhuma notícia encontrada')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('calcula as últimas 24 horas a partir de hoje e permite remover filtros recolhidos', async ({ page }) => {
  const snapshot = await (await page.request.get('/radar.json')).json()
  const last = Math.max(...snapshot.items.map((item: { publishedAt?: string }) => Date.parse(item.publishedAt ?? '') || 0))
  await page.clock.setSystemTime(last + 2 * 86400000)
  await page.goto('/#/radar')
  await page.getByRole('combobox', { name: 'Publicação', exact: true }).selectOption('1')
  await expect(page.getByText('Nenhuma notícia encontrada')).toBeVisible()
  const advanced = page.getByRole('button', { name: 'Mais filtros' })
  await advanced.press('Enter')
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('pt')
  await advanced.press('Enter')
  await page.getByRole('button', { name: 'Remover filtro Português' }).press('Enter')
  await advanced.click()
  await expect(page.getByRole('combobox', { name: 'Idioma', exact: true })).toHaveValue('')
})

test('analisa a notícia escolhida ao lado dos cartões e mantém o acesso à fonte quando falta resumo', async ({ page }, info) => {
  const snapshot = await (await page.request.get('/radar.json')).json()
  const [first, second] = snapshot.items
  const summary = 'A equipe apresentou a identidade do festival. As peças usam letras de diferentes larguras. O projeto foi divulgado na abertura. A programação continua no domingo.'
  await page.route('**/radar.json', route => route.fulfill({ json: {
    ...snapshot, items: [{ ...first, summary }, { ...second, summary: undefined, imageUrl: 'https://storage.ghost.io/radar-fixture.jpg' }], opportunities: [],
  } }))
  await page.route('https://storage.ghost.io/radar-fixture.jpg', route => route.fulfill({ contentType: 'image/jpeg', body: 'invalid image' }))
  await page.goto('/#/radar')
  const cards = page.locator('.news-story')
  const analyze = cards.first().getByRole('button', { name: /^Analisar notícia:/ })
  const panel = page.getByRole('region', { name: 'Assistente Editorial', exact: true })
  const link = cards.first().getByRole('link', { name: first.title, exact: true })
  await expect(link).toHaveAttribute('href', first.url)
  await expect(cards.nth(1).locator('.news-thumbnail span')).toHaveText(second.source)
  await analyze.focus()
  await analyze.press('Enter')
  await expect(panel.getByRole('heading', { name: 'Assistente Editorial' })).toBeFocused()
  await expect(panel).toContainText(first.title)
  await expect(panel).toContainText('Análise baseada no resumo disponível')
  await expect(panel).toContainText('Leitura editorial.')
  await expect(panel).toContainText('O projeto foi divulgado na abertura.')
  await expect(panel).not.toContainText('A programação continua no domingo.')
  await expect(panel).not.toContainText(/SRC-|Dados insuficientes/)
  await expect(panel.getByLabel('Notificações')).toBeHidden()
  await expect(panel.getByRole('heading', { name: 'Como aproveitar essa notícia?' })).toBeVisible()
  const [cardBox, panelBox] = await Promise.all([cards.first().boundingBox(), panel.boundingBox()])
  expect(cardBox!.x + cardBox!.width).toBeLessThan(panelBox!.x)
  expect(cardBox!.y - panelBox!.y).toBeLessThan(45)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(await page.evaluate(() => innerWidth))
  await page.screenshot({ path: info.outputPath('radar-assistente.png') })
  await panel.getByRole('button', { name: 'Dispensar sugestão' }).click()
  await expect(panel.getByRole('heading', { name: 'Como aproveitar essa notícia?' })).toBeHidden()
  await page.keyboard.press('Escape')
  await expect(analyze).toBeFocused()

  await cards.nth(1).getByRole('button', { name: /^Analisar notícia:/ }).click()
  await expect(panel).toContainText(second.title)
  await expect(panel).not.toContainText(first.title)
  await expect(panel).toContainText('Sem um resumo')
  await expect(panel.getByRole('heading', { name: 'Como aproveitar essa notícia?' })).toBeHidden()
  await expect(panel.getByRole('link', { name: 'Ler notícia original' })).toHaveAttribute('href', second.url)
  const search = page.getByRole('searchbox', { name: 'Buscar notícias' })
  await search.fill(first.title)
  await expect(search).toBeFocused()
  await expect(panel.getByText(/Escolha Analisar notícia/)).toBeVisible()
  await page.getByRole('button', { name: 'Limpar filtros' }).click()
  await expect(search).toHaveValue('')
  await expect(cards).toHaveCount(2)
  await panel.getByRole('button', { name: 'Criar post com esta notícia' }).click()
  await expect(page.getByRole('heading', { name: 'Briefing editorial' })).toBeVisible()
})

test('mostra carregamento, permite repetir falhas e respeita o movimento reduzido', async ({ page }) => {
  const snapshot = await (await page.request.get('/radar.json')).json()
  let release!: () => void
  const pending = new Promise<void>(resolve => { release = resolve })
  await page.route('**/radar.json', async route => {
    await pending
    await route.fulfill({ status: 503 })
  })
  await page.goto('/#/radar')
  await expect(page.locator('.news-skeleton').first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Verificando…' })).toBeDisabled()
  release()
  await expect(page.getByRole('alert')).toContainText('Não foi possível carregar as notícias')
  await page.route('**/radar.json', route => route.fulfill({ json: snapshot }))
  await page.getByRole('button', { name: 'Tentar novamente' }).click()
  const card = page.locator('.news-story').first()
  const create = card.getByRole('button', { name: 'Criar post', exact: true })
  await create.hover()
  await expect(card).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, -2)')
  await expect(create).toHaveCSS('background-color', 'rgb(180, 0, 18)')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(card).toHaveCSS('transform', 'none')
  await expect(card).toHaveCSS('transition-duration', '0s')
})
