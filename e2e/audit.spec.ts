import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('audita, localiza, corrige, desfaz e preserva projeto', async ({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/#/studio')
  await page.getByRole('button',{name:'Criar projeto vazio'}).click()
  await page.getByLabel('Projeto',{exact:true}).fill('Auditoria de teste')
  await page.getByRole('button',{name:'Adicionar título',exact:true}).click()
  await page.getByLabel('X',{exact:true}).fill('20')
  await page.getByRole('button',{name:'Auditar design'}).click()
  await page.getByRole('button',{name:'Auditar slide atual'}).click()
  await expect(page.getByRole('heading',{name:'Texto fora da margem segura'})).toBeVisible()
  for(const width of [1024,1280,1440]){await page.setViewportSize({width,height:960});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)}
  await page.getByRole('button',{name:'Localizar no Studio'}).first().click()
  await expect(page.getByLabel('Texto do elemento')).toBeVisible()
  page.on('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Propor correção'}).first().click()
  await expect(page.getByRole('heading',{name:'Texto fora da margem segura'})).toHaveCount(0)
  await page.getByRole('button',{name:'Desfazer última alteração'}).click()
  await page.getByRole('button',{name:'Auditar slide atual'}).click()
  await expect(page.getByRole('heading',{name:'Texto fora da margem segura'})).toBeVisible()
  const jsonEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'Baixar relatório JSON'}).click()
  const report=JSON.parse((await readFile(await (await jsonEvent).path())).toString())
  expect(report.findings.some((f:{ruleId:string})=>f.ruleId==='SAFE_MARGIN')).toBe(true)
  await page.getByRole('button',{name:'Exportar PNG',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('Texto fora da margem segura')
  const pngEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'Exportar com avisos'}).click()
  const png=await readFile(await (await pngEvent).path())
  expect([png.readUInt32BE(16),png.readUInt32BE(20)]).toEqual([1080,1350])
  await page.getByRole('button',{name:'Salvar',exact:true}).click()
  await page.getByRole('link',{name:'Auditoria',exact:true}).click()
  await page.getByLabel('Projeto para auditar').selectOption({label:'Auditoria de teste'})
  await page.getByRole('button',{name:'Auditar todos os slides'}).click()
  await expect(page.getByRole('heading',{name:'Texto fora da margem segura'})).toBeVisible()
  await page.getByRole('button',{name:'Localizar no Studio'}).first().click()
  await expect(page.getByLabel('Projeto',{exact:true})).toHaveValue('Auditoria de teste')
  expect(errors).toEqual([])
})
